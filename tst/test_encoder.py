def test_fnav_interleaving():
    encoded_fnav = ("1000110000011010101010100111001100110001010110100110111101011001"
                    "0111100010010101010101011000110011001110101001011001000010100110"
                    "1000010000000010000000100001101110011001111010110101110000011000"
                    "1011101111111101111111011110010001100110000101001010001111100111"
                    "1010011001100110011010110001000000011100000111010101000110101110"
                    "0011100111101001100101001110111111100011111000101010111001010001"
                    "1111110100111101111100001010100111011000001100100011111110000100"
                    "1001001010010110001001001010101101001110")

    interleaved_fnav = ("1010000001011111100011001111001110000001011111101011100111010000"
                        "1011110101000000001100111100101100010010111011010100000001001110"
                        "1010000101000001001111101111100001110111101111011000110010111011"
                        "1100010000110111110010000011110101000011110111011000111001111001"
                        "1000000111111110000000101101110100101101101000011100000100111110"
                        "1100000100111110111001101001100101100001101101011101100000100101"
                        "1101001000101111100001000111100000011011011000110110110010000011"
                        "1001110001100100110110110011101001000010")
    
    assert GalileoEncoder.interleave_fnav(encoded_fnav) == interleaved_fnav, "no match"
    assert GalileoEncoder.deinterleave_fnav(interleaved_fnav) == encoded_fnav, "no match"

